// ABOUTME: Exercises the read-only Gantt through Display, persistence, and project navigation.
// ABOUTME: Runs against the isolated seeded workspace and checks actual leaf completion counts.

import { expect, test } from '@playwright/test'
import { readSeed } from './support/bd'

test('Gantt shows work sizing and survives saved views and detail navigation', async ({ page }) => {
  await page.goto('/projects')
  await expect(async () => {
    await page.getByRole('button', { name: 'Display', exact: true }).click()
    await expect(page.getByRole('combobox', { name: 'View', exact: true })).toBeVisible({ timeout: 2000 })
  }).toPass()
  await page.getByRole('combobox', { name: 'View', exact: true }).click()
  await page.getByRole('option', { name: 'Gantt', exact: true }).click()
  await page.keyboard.press('Escape')
  const chart = page.getByRole('region', { name: 'Project Gantt', exact: true })
  await expect(chart).toBeVisible()
  await expect(page.getByText(/Width counts leaf subissues/)).toBeHidden()
  await page.getByRole('button', { name: 'Display', exact: true }).click()
  await expect(page.getByText(/Grouped by assignee/)).toBeVisible()
  await expect(page.getByText(/Width counts leaf subissues/)).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page).toHaveURL(/view=gantt/)
  await expect(chart.getByRole('button', { name: 'E2E Epic: 1/3 subissues complete', exact: true })).toBeVisible()
  await expect(chart.getByRole('button', { name: 'Lonely Epic: 0/0 subissues complete', exact: true })).toBeVisible()
  await expect(chart.locator('[draggable="true"]')).toHaveCount(0)
  // The project column stays pinned while the work grid moves, including on a narrow window.
  await page.setViewportSize({ width: 640, height: 800 })
  const scroller = page.getByRole('region', { name: 'Scrollable owner roadmap', exact: true })
  const column = page.getByTestId('gantt-project-column')
  const bar = chart.getByRole('button', { name: 'E2E Epic: 1/3 subissues complete', exact: true })
  const columnBefore = await column.boundingBox()
  const barBefore = await bar.boundingBox()
  expect(columnBefore).not.toBeNull()
  expect(barBefore).not.toBeNull()
  await scroller.evaluate((element) => { element.scrollLeft = 100 })
  await expect.poll(() => scroller.evaluate((element) => element.scrollLeft)).toBe(100)
  const columnAfter = await column.boundingBox()
  const barAfter = await bar.boundingBox()
  expect(columnAfter?.x).toBe(columnBefore?.x)
  expect(barAfter?.x).toBe((barBefore?.x ?? 0) - 100)
  await scroller.evaluate((element) => { element.scrollLeft = 0 })
  await page.setViewportSize({ width: 1280, height: 720 })
  await page.getByRole('button', { name: 'Save current view' }).click()
  await page.getByRole('textbox', { name: 'View name' }).fill('Owner roadmap')
  await page.getByRole('button', { name: 'Save view', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Owner roadmap', exact: true })).toBeVisible()
  await page.reload()
  await expect(chart).toBeVisible()
  await expect(page.getByRole('button', { name: 'Owner roadmap', exact: true })).toBeVisible()
  await expect(async () => {
    await chart.getByRole('button', { name: 'E2E Epic: 1/3 subissues complete', exact: true }).click()
    await expect(page).toHaveURL(new RegExp(`/projects/${readSeed().epicId}`), { timeout: 3000 })
  }).toPass()
  await page.goBack()
  await expect(chart).toBeVisible()
  await page.getByRole('button', { name: 'All projects', exact: true }).click()
  await expect(chart).toBeHidden()
  await page.getByRole('button', { name: 'Owner roadmap', exact: true }).click()
  await expect(chart).toBeVisible()
  await page.getByRole('button', { name: 'Delete view Owner roadmap' }).click()
  await expect(page.getByRole('button', { name: 'Owner roadmap', exact: true })).toBeHidden()
})
